package main

import (
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"go/doc/comment"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"slices"
	"strings"
)

const manifestName = ".agentshield-docs.json"
const generatedMarker = "Generated by agentshield-docs"
const modulePath = "github.com/agentshield-dev/agentshield"

func main() {
	if err := run(os.Args[1:]); err != nil && !errors.Is(err, flag.ErrHelp) {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(args []string) error {
	flags := flag.NewFlagSet("agentshield-docs", flag.ContinueOnError)
	directory := flags.String("output-dir", ".agentshield/docs-reference", "destination directory for generated package documentation")
	root := flags.String("source-root", ".", "repository root containing doc.go files")
	if err := flags.Parse(args); err != nil {
		return err
	}
	if flags.NArg() != 0 {
		return fmt.Errorf("unexpected positional arguments")
	}
	if *directory == "" {
		return fmt.Errorf("--output-dir must not be empty")
	}
	pages, err := generatePages(*root)
	if err != nil {
		return err
	}
	return writeReferences(*directory, pages)
}

type referencePage struct {
	Name    string
	Content string
}

func generatePages(root string) ([]referencePage, error) {
	type packageDoc struct {
		Source, Directory, Package, Text string
	}
	var documents []packageDoc
	imports := make(map[string]string)
	err := fs.WalkDir(os.DirFS(root), ".", func(name string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() {
			if name != "." && (strings.HasPrefix(entry.Name(), ".") || slices.Contains([]string{"node_modules", "vendor", "testdata", "dist", "out", "public", "storybook-static"}, entry.Name())) {
				return fs.SkipDir
			}
			return nil
		}
		if entry.Name() != "doc.go" {
			return nil
		}
		file, err := parser.ParseFile(token.NewFileSet(), filepath.Join(root, filepath.FromSlash(name)), nil, parser.ParseComments|parser.PackageClauseOnly)
		if err != nil {
			return err
		}
		if file.Doc == nil {
			return fmt.Errorf("%s has no package documentation", name)
		}
		directory := path.Dir(name)
		doc := packageDoc{Source: name, Directory: directory, Package: file.Name.Name, Text: file.Doc.Text()}
		documents = append(documents, doc)
		if _, exists := imports[doc.Package]; !exists || strings.HasPrefix(directory, "pkg/") {
			imports[doc.Package] = path.Join(modulePath, directory)
		}
		return nil
	})
	if err != nil {
		return nil, fmt.Errorf("read doc.go files: %w", err)
	}
	if len(documents) == 0 {
		return nil, fmt.Errorf("no doc.go files found in %s", root)
	}
	var pages []referencePage
	var index strings.Builder
	index.WriteString("Package documentation generated from each `doc.go` file. API symbol links point to pkg.go.dev; exported declarations are not copied here.\n\n")
	for _, document := range documents {
		packagePath := path.Join(modulePath, document.Directory)
		parser := comment.Parser{
			LookupSym: func(_, _ string) bool { return true },
			LookupPackage: func(name string) (string, bool) {
				importPath, found := imports[name]
				return importPath, found
			},
		}
		printer := comment.Printer{HeadingLevel: 2, DocLinkURL: func(link *comment.DocLink) string {
			importPath := link.ImportPath
			if importPath == "" {
				importPath = packagePath
			}
			url := "https://pkg.go.dev/" + importPath
			if link.Name != "" {
				url += "#"
				if link.Recv != "" {
					url += link.Recv + "."
				}
				url += link.Name
			}
			return url
		}}
		body := fmt.Sprintf("Source: [%s](https://github.com/agentshield-dev/agentshield/blob/main/%s).\n\n%s", document.Source, document.Source, printer.Markdown(parser.Parse(document.Text)))
		name := strings.ReplaceAll(document.Directory, "/", "-")
		if name == "." {
			name = "root"
		}
		pages = append(pages, newPage("go/"+name+".md", document.Directory, body))
		fmt.Fprintf(&index, "- [%s](/docs/reference/go/%s/)\n", document.Directory, name)
	}
	pages = append(pages, newPage("go/_index.md", "Package documentation", index.String()))
	pages = append(pages, newPage("_index.md", "Reference", "[Package documentation](/docs/reference/go/), generated from Go package comments."))
	return pages, nil
}

func newPage(name, title, body string) referencePage {
	return referencePage{Name: name, Content: fmt.Sprintf("---\ntitle: %q\nweight: 80\n---\n<!-- %s. Do not edit manually. -->\n\n%s\n", title, generatedMarker, strings.TrimSpace(body))}
}

func writeReferences(directory string, pages []referencePage) error {
	if err := os.MkdirAll(directory, 0755); err != nil {
		return err
	}
	root, err := os.OpenRoot(directory)
	if err != nil {
		return err
	}
	defer root.Close()
	var previous []string
	if content, err := root.ReadFile(manifestName); err == nil {
		if err := json.Unmarshal(content, &previous); err != nil {
			return fmt.Errorf("decode reference manifest: %w", err)
		}
	} else if !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	current := make(map[string]bool)
	var names []string
	for _, page := range pages {
		if current[page.Name] {
			return fmt.Errorf("duplicate generated page %q", page.Name)
		}
		current[page.Name] = true
		names = append(names, page.Name)
	}
	for _, name := range append(slices.Clone(names), previous...) {
		if !fs.ValidPath(name) || !strings.HasSuffix(name, ".md") {
			return fmt.Errorf("invalid generated page path %q", name)
		}
		if content, err := root.ReadFile(name); err == nil {
			if !strings.Contains(string(content), generatedMarker) {
				return fmt.Errorf("refusing to replace or remove authored page %q", name)
			}
		} else if !errors.Is(err, fs.ErrNotExist) {
			return fmt.Errorf("inspect reference %s: %w", name, err)
		}
	}
	for _, page := range pages {
		if err := root.MkdirAll(path.Dir(page.Name), 0755); err != nil {
			return err
		}
		if err := writeRootFile(root, page.Name, page.Content); err != nil {
			return err
		}
	}
	for _, name := range previous {
		if !current[name] {
			if err := root.Remove(name); err != nil && !errors.Is(err, fs.ErrNotExist) {
				return fmt.Errorf("remove stale generated page %s: %w", name, err)
			}
		}
	}
	slices.Sort(names)
	manifest, err := json.MarshalIndent(names, "", "  ")
	if err != nil {
		return err
	}
	return writeRootFile(root, manifestName, string(manifest)+"\n")
}

func writeRootFile(root *os.Root, name, content string) error {
	file, err := root.OpenFile(name, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, 0644)
	if err != nil {
		return fmt.Errorf("open reference %s: %w", name, err)
	}
	if _, err := file.WriteString(content); err != nil {
		_ = file.Close()
		return fmt.Errorf("write reference %s: %w", name, err)
	}
	return file.Close()
}
